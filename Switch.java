class Switch
{
	public static void main (String[]args)
	{
		int i=10;
		switch(i)
		{
			case 5:
			System.out.println("Five");
			break;
			case 10:
			System.out.println("ten");
			break;
			case 15:
			System.out.println("Fifteen");
			break;
			default:
			System.out.println("default");
			break;
		}
	}
}